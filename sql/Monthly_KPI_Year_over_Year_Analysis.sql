WITH monthly_data AS (
    SELECT
        TO_NUMBER(SUBSTR(MONTH, 1, 4)) AS KPI_YEAR,
        TO_NUMBER(SUBSTR(MONTH, 6, 2)) AS MONTH_SORT,
        MAU,
        NEW_REGISTRATIONS,
        ACTIVATION_RATE_30D,
        POS_USERS_SHARE,
        P2P_USERS_SHARE,
        INACTIVE_90D_SHARE
    FROM MONTHLY_KPI_CLEAN
),
yoy_comparison AS (
    SELECT
        curr.KPI_YEAR,
        curr.MONTH_SORT,

        curr.MAU AS MAU_2026,
        prev.MAU AS MAU_2025,

        curr.NEW_REGISTRATIONS AS REGISTRATIONS_2026,
        prev.NEW_REGISTRATIONS AS REGISTRATIONS_2025,

        curr.ACTIVATION_RATE_30D AS ACTIVATION_2026,
        prev.ACTIVATION_RATE_30D AS ACTIVATION_2025,

        curr.POS_USERS_SHARE AS POS_SHARE_2026,
        prev.POS_USERS_SHARE AS POS_SHARE_2025,

        curr.P2P_USERS_SHARE AS P2P_SHARE_2026,
        prev.P2P_USERS_SHARE AS P2P_SHARE_2025,

        curr.INACTIVE_90D_SHARE AS INACTIVE_2026,
        prev.INACTIVE_90D_SHARE AS INACTIVE_2025

    FROM monthly_data curr
    JOIN monthly_data prev
        ON curr.MONTH_SORT = prev.MONTH_SORT
        AND curr.KPI_YEAR = prev.KPI_YEAR + 1

    WHERE curr.KPI_YEAR = 2026
      AND curr.MONTH_SORT BETWEEN 5 AND 10
)
SELECT
    TO_CHAR(
        TO_DATE(
            '2026-' || LPAD(TO_CHAR(MONTH_SORT), 2, '0') || '-01',
            'YYYY-MM-DD'
        ),
        'MON YYYY',
        'NLS_DATE_LANGUAGE=ENGLISH'
    ) AS MONTH_YEAR,

    MAU_2025,
    MAU_2026,
    ROUND(
        (MAU_2026 - MAU_2025) * 100.0 /
        NULLIF(MAU_2025, 0), 2
    ) AS MAU_YOY_PCT,

    REGISTRATIONS_2025,
    REGISTRATIONS_2026,
    ROUND(
        (REGISTRATIONS_2026 - REGISTRATIONS_2025) * 100.0 /
        NULLIF(REGISTRATIONS_2025, 0), 2
    ) AS REGISTRATIONS_YOY_PCT,

    ACTIVATION_2025,
    ACTIVATION_2026,
    ROUND(
        (ACTIVATION_2026 - ACTIVATION_2025) * 100, 2
    ) AS ACTIVATION_CHANGE_PP,

    POS_SHARE_2025,
    POS_SHARE_2026,
    ROUND(
        (POS_SHARE_2026 - POS_SHARE_2025) * 100, 2
    ) AS POS_CHANGE_PP,

    P2P_SHARE_2025,
    P2P_SHARE_2026,
    ROUND(
        (P2P_SHARE_2026 - P2P_SHARE_2025) * 100, 2
    ) AS P2P_CHANGE_PP,

    INACTIVE_2025,
    INACTIVE_2026,
    ROUND(
        (INACTIVE_2026 - INACTIVE_2025) * 100, 2
    ) AS INACTIVE_CHANGE_PP

FROM yoy_comparison
ORDER BY MONTH_SORT;