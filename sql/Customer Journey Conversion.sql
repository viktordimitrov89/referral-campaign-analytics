

WITH JOURNEY AS (

    SELECT 1 AS STAGE_ORDER, 'Invite' AS JOURNEY_STAGE,
           COUNT(DISTINCT INVITE_ID) AS CUSTOMERS
    FROM REFERRALS_CLEAN

    UNION ALL

    SELECT 2, 'Phone entered',
           COUNT(DISTINCT CASE WHEN PHONE_ENTERED_DATE IS NOT NULL
                               THEN INVITE_ID END)
    FROM REFERRALS_CLEAN

    UNION ALL

    SELECT 3, 'Registration',
           COUNT(DISTINCT CASE WHEN REGISTRATION_DATE IS NOT NULL
                               THEN INVITE_ID END)
    FROM REFERRALS_CLEAN

    UNION ALL

    SELECT 4, 'Card requested',
           COUNT(DISTINCT CASE WHEN CARD_ISSUED_DATE IS NOT NULL
                               THEN INVITE_ID END)
    FROM REFERRALS_CLEAN

    UNION ALL

    SELECT 5, 'Card activated',
           COUNT(DISTINCT CASE WHEN CARD_ACTIVATED_DATE IS NOT NULL
                               THEN INVITE_ID END)
    FROM REFERRALS_CLEAN

    UNION ALL

    SELECT 6, 'First POS',
           COUNT(DISTINCT CASE WHEN FIRST_POS_DATE IS NOT NULL
                               THEN INVITE_ID END)
    FROM REFERRALS_CLEAN

    UNION ALL

    SELECT 7, 'Reward paid',
           COUNT(DISTINCT CASE WHEN REWARD_PAID = 1
                               THEN INVITE_ID END)
    FROM REFERRALS_CLEAN
),

JOURNEY_CALCULATED AS (
    SELECT
        STAGE_ORDER,
        JOURNEY_STAGE,
        CUSTOMERS,
        LAG(CUSTOMERS) OVER (ORDER BY STAGE_ORDER) AS PREVIOUS_STAGE
    FROM JOURNEY
)

SELECT
    STAGE_ORDER,
    JOURNEY_STAGE,
    CUSTOMERS,
    PREVIOUS_STAGE - CUSTOMERS AS ABSOLUTE_DROPOFF,

    ROUND(
        (PREVIOUS_STAGE - CUSTOMERS)
        / NULLIF(PREVIOUS_STAGE, 0) * 100,
        2
    ) AS DROPOFF_PERCENT,

    ROUND(
        CUSTOMERS / NULLIF(PREVIOUS_STAGE, 0) * 100,
        2
    ) AS CONVERSION_PERCENT,

    ROUND(
        CUSTOMERS / NULLIF(
            FIRST_VALUE(CUSTOMERS) OVER (ORDER BY STAGE_ORDER), 0
        ) * 100,
        2
    ) AS OVERALL_CONVERSION_PERCENT

FROM JOURNEY_CALCULATED
ORDER BY STAGE_ORDER;

