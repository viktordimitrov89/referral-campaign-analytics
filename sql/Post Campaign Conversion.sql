-- Analysis: Invited Customer POS Activity by Inviter Age Group

SELECT
    R.INVITER_AGE_GROUP,
    COUNT(DISTINCT R.INVITED_CLIENT_ID) AS INVITED_CUSTOMERS,
    COUNT(DISTINCT A.INVITED_CLIENT_ID) AS ACTIVE_CUSTOMERS,
    SUM(A.POS_TXN_COUNT) AS TOTAL_POS_TRANSACTIONS,
    ROUND(SUM(A.POS_AMOUNT_EUR), 2) AS TOTAL_POS_AMOUNT_EUR,
    ROUND(AVG(A.POS_AMOUNT_EUR), 2) AS AVG_MONTHLY_POS_AMOUNT_EUR
FROM REFERRALS_CLEAN R
LEFT JOIN INVITED_ACTIVITY_CLEAN A
    ON R.INVITED_CLIENT_ID = A.INVITED_CLIENT_ID
WHERE R.INVITED_CLIENT_ID IS NOT NULL
GROUP BY R.INVITER_AGE_GROUP
ORDER BY R.INVITER_AGE_GROUP;

-- Analysis: Rewards and POS Activity by Inviter Age Group

WITH REFERRAL_BY_CLIENT AS (
    SELECT
        INVITED_CLIENT_ID,
        INVITER_AGE_GROUP,
        MAX(REWARD_PAID) AS REWARD_PAID
    FROM REFERRALS_CLEAN
    WHERE INVITED_CLIENT_ID IS NOT NULL
    GROUP BY
        INVITED_CLIENT_ID,
        INVITER_AGE_GROUP
),
ACTIVITY_BY_CLIENT AS (
    SELECT
        INVITED_CLIENT_ID,
        SUM(POS_TXN_COUNT) AS TOTAL_POS_TRANSACTIONS,
        SUM(POS_AMOUNT_EUR) AS TOTAL_POS_AMOUNT_EUR
    FROM INVITED_ACTIVITY_CLEAN
    GROUP BY INVITED_CLIENT_ID
)
SELECT
    R.INVITER_AGE_GROUP,
    COUNT(DISTINCT R.INVITED_CLIENT_ID) AS INVITED_CUSTOMERS,
    COUNT(DISTINCT CASE
        WHEN R.REWARD_PAID = 1 THEN R.INVITED_CLIENT_ID
    END) AS REWARDS_PAID,
    ROUND(
        COUNT(DISTINCT CASE
            WHEN R.REWARD_PAID = 1 THEN R.INVITED_CLIENT_ID
        END)
        / NULLIF(COUNT(DISTINCT R.INVITED_CLIENT_ID), 0) * 100,
        2
    ) AS REWARD_RATE_PERCENT,
    SUM(NVL(A.TOTAL_POS_TRANSACTIONS, 0)) AS TOTAL_POS_TRANSACTIONS,
    ROUND(SUM(NVL(A.TOTAL_POS_AMOUNT_EUR, 0)), 2)
        AS TOTAL_POS_AMOUNT_EUR,
    ROUND(
        AVG(A.TOTAL_POS_AMOUNT_EUR), 2
    ) AS AVG_POS_AMOUNT_PER_CUSTOMER_EUR
FROM REFERRAL_BY_CLIENT R
LEFT JOIN ACTIVITY_BY_CLIENT A
    ON R.INVITED_CLIENT_ID = A.INVITED_CLIENT_ID
GROUP BY R.INVITER_AGE_GROUP
ORDER BY R.INVITER_AGE_GROUP;

