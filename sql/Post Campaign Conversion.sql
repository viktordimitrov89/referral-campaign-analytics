--Analysis – Registration Drop-off by Age Group

SELECT
    NVL(INVITER_AGE_GROUP, 'Missing') AS INVITER_AGE_GROUP,

    COUNT(*) AS TOTAL_REFERRALS,

    SUM(CASE
        WHEN INVITED_CLIENT_ID IS NULL THEN 1
        ELSE 0
    END) AS WITHOUT_INVITED_CLIENT_ID,

    SUM(CASE
        WHEN INVITED_CLIENT_ID IS NULL
         AND PHONE_ENTERED_DATE IS NOT NULL THEN 1
        ELSE 0
    END) AS WITH_PHONE_ENTERED,

    SUM(CASE
        WHEN INVITED_CLIENT_ID IS NULL
         AND PHONE_ENTERED_DATE IS NULL THEN 1
        ELSE 0
    END) AS WITHOUT_PHONE_ENTERED,

    SUM(CASE
        WHEN INVITED_CLIENT_ID IS NULL
         AND PHONE_ENTERED_DATE IS NOT NULL
         AND REGISTRATION_DATE IS NOT NULL THEN 1
        ELSE 0
    END) AS WITH_REGISTRATION_DATE,

    SUM(CASE
        WHEN INVITED_CLIENT_ID IS NULL
         AND PHONE_ENTERED_DATE IS NOT NULL
         AND CARD_ISSUED_DATE IS NOT NULL THEN 1
        ELSE 0
    END) AS WITH_CARD_ISSUED_DATE

FROM REFERRALS_CLEAN
GROUP BY NVL(INVITER_AGE_GROUP, 'Missing')
ORDER BY
    CASE NVL(INVITER_AGE_GROUP, 'Missing')
        WHEN '18-25' THEN 1
        WHEN '26-35' THEN 2
        WHEN '36-45' THEN 3
        WHEN '46-60' THEN 4
        WHEN '60+' THEN 5
        ELSE 6
    END;