-- Analysis: Campaign Completion Within vs Outside Campaign Period

SELECT
    CASE
        WHEN REGISTRATION_DATE BETWEEN DATE '2026-07-27'
                                   AND DATE '2026-08-31'
         AND CARD_ISSUED_DATE BETWEEN DATE '2026-07-27'
                                  AND DATE '2026-08-31'
         AND CARD_ACTIVATED_DATE BETWEEN DATE '2026-07-27'
                                     AND DATE '2026-08-31'
         AND FIRST_POS_DATE BETWEEN DATE '2026-07-27'
                                AND DATE '2026-08-31'
         AND FIRST_POS_AMOUNT_EUR >= 5
        THEN 'Completed Within Campaign'

        WHEN REGISTRATION_DATE IS NOT NULL
         AND CARD_ISSUED_DATE IS NOT NULL
         AND CARD_ACTIVATED_DATE IS NOT NULL
         AND FIRST_POS_DATE IS NOT NULL
         AND (
             REGISTRATION_DATE NOT BETWEEN DATE '2026-07-27'
                                       AND DATE '2026-08-31'
             OR CARD_ISSUED_DATE NOT BETWEEN DATE '2026-07-27'
                                         AND DATE '2026-08-31'
             OR CARD_ACTIVATED_DATE NOT BETWEEN DATE '2026-07-27'
                                            AND DATE '2026-08-31'
             OR FIRST_POS_DATE NOT BETWEEN DATE '2026-07-27'
                                       AND DATE '2026-08-31'
         )
        THEN 'Completed Outside Campaign'

        ELSE 'Incomplete / Not Eligible'
    END AS COMPLETION_STATUS,
    COUNT(DISTINCT INVITE_ID) AS REFERRAL_COUNT
FROM REFERRALS_CLEAN
GROUP BY
    CASE
        WHEN REGISTRATION_DATE BETWEEN DATE '2026-07-27'
                                   AND DATE '2026-08-31'
         AND CARD_ISSUED_DATE BETWEEN DATE '2026-07-27'
                                  AND DATE '2026-08-31'
         AND CARD_ACTIVATED_DATE BETWEEN DATE '2026-07-27'
                                     AND DATE '2026-08-31'
         AND FIRST_POS_DATE BETWEEN DATE '2026-07-27'
                                AND DATE '2026-08-31'
         AND FIRST_POS_AMOUNT_EUR >= 5
        THEN 'Completed Within Campaign'
        WHEN REGISTRATION_DATE IS NOT NULL
         AND CARD_ISSUED_DATE IS NOT NULL
         AND CARD_ACTIVATED_DATE IS NOT NULL
         AND FIRST_POS_DATE IS NOT NULL
         AND (
             REGISTRATION_DATE NOT BETWEEN DATE '2026-07-27'
                                       AND DATE '2026-08-31'
             OR CARD_ISSUED_DATE NOT BETWEEN DATE '2026-07-27'
                                         AND DATE '2026-08-31'
             OR CARD_ACTIVATED_DATE NOT BETWEEN DATE '2026-07-27'
                                            AND DATE '2026-08-31'
             OR FIRST_POS_DATE NOT BETWEEN DATE '2026-07-27'
                                       AND DATE '2026-08-31'
         )
        THEN 'Completed Outside Campaign'
        ELSE 'Incomplete / Not Eligible'
    END
ORDER BY COMPLETION_STATUS;

-- Analysis: Campaign Completion Within vs Outside Campaign Period

WITH CLASSIFIED_REFERRALS AS (
    SELECT DISTINCT
        INVITE_ID,
        CASE
            WHEN REGISTRATION_DATE IS NULL
              OR CARD_ISSUED_DATE IS NULL
              OR CARD_ACTIVATED_DATE IS NULL
              OR FIRST_POS_DATE IS NULL
            THEN 'Incomplete Dates'

            WHEN REGISTRATION_DATE > DATE '2026-08-31'
              OR CARD_ISSUED_DATE > DATE '2026-08-31'
              OR CARD_ACTIVATED_DATE > DATE '2026-08-31'
              OR FIRST_POS_DATE > DATE '2026-08-31'
            THEN 'Completed Outside Campaign'

            WHEN REGISTRATION_DATE >= DATE '2026-07-27'
             AND CARD_ISSUED_DATE >= DATE '2026-07-27'
             AND CARD_ACTIVATED_DATE >= DATE '2026-07-27'
             AND FIRST_POS_DATE >= DATE '2026-07-27'
             AND FIRST_POS_AMOUNT_EUR >= 5
            THEN 'Completed Within Campaign'

            ELSE 'Other Complete Records'
        END AS COMPLETION_STATUS
    FROM REFERRALS_CLEAN
),
SUMMARY AS (
    SELECT
        COMPLETION_STATUS,
        COUNT(DISTINCT INVITE_ID) AS REFERRAL_COUNT
    FROM CLASSIFIED_REFERRALS
    GROUP BY COMPLETION_STATUS
),
TOTAL AS (
    SELECT COUNT(DISTINCT INVITE_ID) AS TOTAL_REFERRALS
    FROM REFERRALS_CLEAN
)
SELECT
    S.COMPLETION_STATUS,
    S.REFERRAL_COUNT,
    ROUND(
        S.REFERRAL_COUNT / T.TOTAL_REFERRALS * 100,
        2
    ) AS PERCENTAGE
FROM SUMMARY S
CROSS JOIN TOTAL T

UNION ALL

SELECT
    'TOTAL',
    TOTAL_REFERRALS,
    100.00
FROM TOTAL

ORDER BY 1;

