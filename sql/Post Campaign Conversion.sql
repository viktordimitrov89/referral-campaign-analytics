    COUNT(DISTINCT CASE
        WHEN REGISTRATION_DATE >= DATE '2026-09-01'
        THEN INVITE_ID
    END) AS REGISTRATION_AFTER_CAMPAIGN,

    COUNT(DISTINCT CASE
        WHEN CARD_ISSUED_DATE >= DATE '2026-09-01'
        THEN INVITE_ID
    END) AS CARD_REQUESTED_AFTER_CAMPAIGN,

    COUNT(DISTINCT CASE
        WHEN CARD_ACTIVATED_DATE >= DATE '2026-09-01'
        THEN INVITE_ID
    END) AS CARD_ACTIVATED_AFTER_CAMPAIGN,

    COUNT(DISTINCT CASE
        WHEN FIRST_POS_DATE >= DATE '2026-09-01'
        THEN INVITE_ID
    END) AS FIRST_POS_AFTER_CAMPAIGN

FROM REFERRALS_CLEAN;

-- Analysis: Referrals Completing Required Steps After Campaign

SELECT
    COUNT(DISTINCT INVITE_ID) AS POS_AFTER_CAMPAIGN,
    COUNT(DISTINCT CASE
        WHEN REGISTRATION_DATE IS NOT NULL
         AND CARD_ACTIVATED_DATE IS NOT NULL
        THEN INVITE_ID
    END) AS ALL_THREE_DATES_AVAILABLE
FROM REFERRALS_CLEAN
WHERE FIRST_POS_DATE >= DATE '2026-09-01';

-- Analysis: POS Amount Validation After Campaign

SELECT
    COUNT(DISTINCT INVITE_ID) AS TOTAL_REFERRALS,
    COUNT(DISTINCT CASE
        WHEN FIRST_POS_AMOUNT_EUR >= 5
        THEN INVITE_ID
    END) AS POS_AMOUNT_AT_LEAST_5,
    COUNT(DISTINCT CASE
        WHEN FIRST_POS_AMOUNT_EUR < 5
        THEN INVITE_ID
    END) AS POS_AMOUNT_BELOW_5,
    COUNT(DISTINCT CASE
        WHEN FIRST_POS_AMOUNT_EUR IS NULL
        THEN INVITE_ID
    END) AS POS_AMOUNT_MISSING
FROM REFERRALS_CLEAN
WHERE FIRST_POS_DATE >= DATE '2026-09-01';

