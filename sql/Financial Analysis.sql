--Total Referral Reward Cost

SELECT
    COUNT(DISTINCT INVITE_ID) AS REWARDS_PAID,
    COUNT(DISTINCT INVITER_ID) AS UNIQUE_INVITERS_REWARDED,
    COUNT(DISTINCT INVITE_ID) * 40 AS TOTAL_REWARD_COST_EUR
FROM REFERRALS_CLEAN
WHERE REWARD_PAID = 1;

--Rewards_Limit_Check

SELECT
    INVITER_ID,
    COUNT(DISTINCT INVITE_ID) AS REWARDS_PAID,
    COUNT(DISTINCT INVITE_ID) - 5 AS EXCESS_REWARDS
FROM REFERRALS_CLEAN
WHERE REWARD_PAID = 1
GROUP BY INVITER_ID
HAVING COUNT(DISTINCT INVITE_ID) > 5
ORDER BY REWARDS_PAID DESC;

--Financial_Analysis

WITH financial_base AS (
    SELECT
        COUNT(DISTINCT CASE
            WHEN REWARD_PAID = 1 THEN INVITE_ID
        END) AS REWARDS_PAID,

        COUNT(DISTINCT CASE
            WHEN CARD_ACTIVATED_DATE IS NOT NULL THEN INVITE_ID
        END) AS ACTIVATED_CARDS,

        COUNT(DISTINCT CASE
            WHEN FIRST_POS_DATE IS NOT NULL THEN INVITE_ID
        END) AS FIRST_POS_CUSTOMERS

    FROM REFERRALS_CLEAN
),
financial_metrics AS (
    SELECT
        REWARDS_PAID,
        ACTIVATED_CARDS,
        FIRST_POS_CUSTOMERS,
        REWARDS_PAID * 40 AS TOTAL_REWARD_COST_EUR,
        3.10 AS MONTHLY_REVENUE_PER_CARD_EUR
    FROM financial_base
)
SELECT
    REWARDS_PAID,
    ACTIVATED_CARDS,
    FIRST_POS_CUSTOMERS,
    TOTAL_REWARD_COST_EUR,

    ROUND(
        TOTAL_REWARD_COST_EUR / NULLIF(ACTIVATED_CARDS, 0),
        2
    ) AS CAC_PER_ACTIVATED_CARD,

    ROUND(
        TOTAL_REWARD_COST_EUR / NULLIF(FIRST_POS_CUSTOMERS, 0),
        2
    ) AS CAC_PER_FIRST_POS_CUSTOMER,

    MONTHLY_REVENUE_PER_CARD_EUR,

    ROUND(
        (TOTAL_REWARD_COST_EUR / NULLIF(ACTIVATED_CARDS, 0))
        / MONTHLY_REVENUE_PER_CARD_EUR,
        2
    ) AS PAYBACK_ACTIVATED_CARD_MONTHS,

    ROUND(
        (TOTAL_REWARD_COST_EUR / NULLIF(FIRST_POS_CUSTOMERS, 0))
        / MONTHLY_REVENUE_PER_CARD_EUR,
        2
    ) AS PAYBACK_FIRST_POS_MONTHS

FROM financial_metrics;

--Rewards_Cap_Impact

WITH ranked_rewards AS (
    SELECT
        INVITER_ID,
        INVITE_ID,
        FIRST_POS_DATE,
        ROW_NUMBER() OVER (
            PARTITION BY INVITER_ID
            ORDER BY FIRST_POS_DATE NULLS LAST, INVITE_ID
        ) AS REWARD_RANK
    FROM REFERRALS_CLEAN
    WHERE REWARD_PAID = 1
)
SELECT
    COUNT(*) AS TOTAL_REWARDS,
    SUM(CASE WHEN REWARD_RANK <= 5 THEN 1 ELSE 0 END)
        AS WITHIN_FIRST_5,
    SUM(CASE WHEN REWARD_RANK > 5 THEN 1 ELSE 0 END)
        AS ABOVE_5_REWARDS,
    SUM(CASE WHEN REWARD_RANK > 5 THEN 40 ELSE 0 END)
        AS POTENTIAL_EXCESS_COST_EUR
FROM ranked_rewards;

--Financial Scenario Comparison

WITH ranked_rewards AS (
    SELECT
        INVITER_ID,
        INVITE_ID,
        ROW_NUMBER() OVER (
            PARTITION BY INVITER_ID
            ORDER BY FIRST_POS_DATE NULLS LAST, INVITE_ID
        ) AS REWARD_RANK
    FROM REFERRALS_CLEAN
    WHERE REWARD_PAID = 1
),
reward_costs AS (
    SELECT
        COUNT(*) * 40 AS ACTUAL_COST_EUR,
        SUM(CASE WHEN REWARD_RANK <= 5 THEN 40 ELSE 0 END)
            AS POTENTIAL_CAPPED_COST_EUR
    FROM ranked_rewards
),
customer_counts AS (
    SELECT
        COUNT(DISTINCT CASE
            WHEN CARD_ACTIVATED_DATE IS NOT NULL THEN INVITE_ID
        END) AS ACTIVATED_CARDS,
        COUNT(DISTINCT CASE
            WHEN FIRST_POS_DATE IS NOT NULL THEN INVITE_ID
        END) AS FIRST_POS_CUSTOMERS
    FROM REFERRALS_CLEAN
)
SELECT
    'Reported cost' AS SCENARIO,
    r.ACTUAL_COST_EUR AS REWARD_COST_EUR,
    c.ACTIVATED_CARDS,
    c.FIRST_POS_CUSTOMERS,
    ROUND(r.ACTUAL_COST_EUR / NULLIF(c.ACTIVATED_CARDS, 0), 2)
        AS CAC_PER_ACTIVATED_CARD,
    ROUND(r.ACTUAL_COST_EUR / NULLIF(c.FIRST_POS_CUSTOMERS, 0), 2)
        AS CAC_PER_FIRST_POS,
    ROUND(r.ACTUAL_COST_EUR / NULLIF(c.ACTIVATED_CARDS, 0) / 3.10, 2)
        AS PAYBACK_ACTIVATED_MONTHS,
    ROUND(r.ACTUAL_COST_EUR / NULLIF(c.FIRST_POS_CUSTOMERS, 0) / 3.10, 2)
        AS PAYBACK_FIRST_POS_MONTHS
FROM reward_costs r
CROSS JOIN customer_counts c

UNION ALL

SELECT
    'Potential capped cost' AS SCENARIO,
    r.POTENTIAL_CAPPED_COST_EUR,
    c.ACTIVATED_CARDS,
    c.FIRST_POS_CUSTOMERS,
    ROUND(r.POTENTIAL_CAPPED_COST_EUR / NULLIF(c.ACTIVATED_CARDS, 0), 2),
    ROUND(r.POTENTIAL_CAPPED_COST_EUR / NULLIF(c.FIRST_POS_CUSTOMERS, 0), 2),
    ROUND(r.POTENTIAL_CAPPED_COST_EUR / NULLIF(c.ACTIVATED_CARDS, 0) / 3.10, 2),
    ROUND(r.POTENTIAL_CAPPED_COST_EUR / NULLIF(c.FIRST_POS_CUSTOMERS, 0) / 3.10, 2)
FROM reward_costs r
CROSS JOIN customer_counts c;

--Revenue_Return_Projection

WITH assumptions AS (
    SELECT
        3.10 AS MONTHLY_REVENUE_EUR,
        13.75 AS CAC_REPORTED_EUR,
        23.84 AS CAC_FIRST_POS_EUR,
        12 AS PROJECTION_MONTHS
    FROM DUAL
)
SELECT
    MONTHLY_REVENUE_EUR,
    PROJECTION_MONTHS,
    ROUND(MONTHLY_REVENUE_EUR * 6, 2) AS REVENUE_6_MONTHS,
    ROUND(MONTHLY_REVENUE_EUR * 12, 2) AS REVENUE_12_MONTHS,

    ROUND(
        MONTHLY_REVENUE_EUR * 12 - CAC_REPORTED_EUR, 2
    ) AS NET_REVENUE_AFTER_ACTIVATED_CAC,

    ROUND(
        MONTHLY_REVENUE_EUR * 12 - CAC_FIRST_POS_EUR, 2
    ) AS NET_REVENUE_AFTER_FIRST_POS_CAC

FROM assumptions;

--Short_Term_Retention

WITH september_active AS (
    SELECT DISTINCT
        INVITED_CLIENT_ID
    FROM INVITED_ACTIVITY_CLEAN
    WHERE MONTH = '2026-09'
      AND POS_TXN_COUNT > 0
),
october_active AS (
    SELECT DISTINCT
        INVITED_CLIENT_ID
    FROM INVITED_ACTIVITY_CLEAN
    WHERE MONTH = '2026-10'
      AND POS_TXN_COUNT > 0
),
retention AS (
    SELECT
        COUNT(*) AS SEPTEMBER_ACTIVE_CUSTOMERS,
        COUNT(o.INVITED_CLIENT_ID) AS RETAINED_CUSTOMERS
    FROM september_active s
    LEFT JOIN october_active o
        ON s.INVITED_CLIENT_ID = o.INVITED_CLIENT_ID
)
SELECT
    SEPTEMBER_ACTIVE_CUSTOMERS,
    RETAINED_CUSTOMERS,
    SEPTEMBER_ACTIVE_CUSTOMERS - RETAINED_CUSTOMERS
        AS NOT_RETAINED_CUSTOMERS,
    ROUND(
        RETAINED_CUSTOMERS * 100.0 /
        NULLIF(SEPTEMBER_ACTIVE_CUSTOMERS, 0),
        2
    ) AS RETENTION_RATE_PCT,
    ROUND(
        (SEPTEMBER_ACTIVE_CUSTOMERS - RETAINED_CUSTOMERS) * 100.0 /
        NULLIF(SEPTEMBER_ACTIVE_CUSTOMERS, 0),
        2
    ) AS CHURN_RATE_PCT
FROM retention;